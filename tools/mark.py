#!/usr/bin/env python3
"""Draw the T32 mark from Public Sans outlines and write it out as SVG.

The mark is the name set in Public Sans at weight 720, spaced by hand, with a
square full stop: the marked cell of the zoom figure, one part in 32. Glyphs
are converted to paths here, so the mark looks the same everywhere, font or no
font. Run it after `npm ci` in web/ (for the font), from the repository root:

    python3 -m venv .venv && .venv/bin/pip install fonttools brotli
    .venv/bin/python tools/mark.py

It writes web/src/lib/mark.ts (the paths the site draws inline),
web/static/mark.svg and web/static/favicon.svg. The output is deterministic,
so a diff after running it means the drawing changed.
"""

from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "web/node_modules/@fontsource-variable/public-sans/files/public-sans-latin-wght-normal.woff2"

WEIGHT = 720
# Ink-to-ink gaps after T and after 3, in font units. T's open arms read as
# space, so it sits closer to the 3 than the 3 does to the 2.
GAPS = (40, 110)
# The full stop: as wide as the T's crossbar is thick, one 3-to-2 gap after the 2.
CELL = 268
CELL_GAP = 110
# Drawing units: cap height is 32.
CAP_UNITS = 32
# Favicon: a 32-unit tile, the name alone (the full stop is lost at 16 pixels).
TILE = 32
TILE_PAD = 4
FAVICON_WEIGHT = 760

# The light and dark values of --ink, --paper and --accent in web/src/app.css.
INK, PAPER, ACCENT = "#1b1b19", "#fbfaf6", "#1d4f86"
DARK_INK, DARK_PAPER, DARK_ACCENT = "#e8e5de", "#141413", "#93b6df"


def num(v: float) -> str:
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def outline(weight: float, scale: float, x0: float, baseline: float) -> tuple[str, float, float, float]:
    """The name as one path, its left edge at x0. Returns (d, right, top, bottom)."""
    font = instantiateVariableFont(TTFont(FONT), {"wght": weight})
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    d, right, top, bottom = [], None, baseline, baseline
    for i, ch in enumerate("T32"):
        g = glyphs[cmap[ord(ch)]]
        bounds = BoundsPen(glyphs)
        g.draw(bounds)
        left, low, r, high = bounds.bounds
        x = x0 - left * scale if right is None else right + GAPS[i - 1] * scale - left * scale
        pen = SVGPathPen(glyphs, ntos=num)
        g.draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
        d.append(pen.getCommands())
        right = x + r * scale
        top, bottom = min(top, baseline - high * scale), max(bottom, baseline - low * scale)
    return "".join(d), right, top, bottom


def main() -> None:
    cap = TTFont(FONT)["OS/2"].sCapHeight
    s = CAP_UNITS / cap
    d, right, top, bottom = outline(WEIGHT, s, 0, CAP_UNITS)
    cx, cw = right + CELL_GAP * s, CELL * s
    width = cx + cw
    cell = (num(cx), num(CAP_UNITS - cw), num(cw))

    (ROOT / "web/src/lib/mark.ts").write_text(
        "// Generated by tools/mark.py from Public Sans; do not edit by hand.\n"
        "// Units: cap height 32, baseline at y = 32. Round letters overshoot it slightly.\n"
        f"export const MARK = {{\n"
        f"\twidth: {num(width)},\n"
        f"\ttop: {num(top)},\n"
        f"\tbottom: {num(bottom)},\n"
        f"\tname: '{d}',\n"
        f"\tcell: {{ x: {cell[0]}, y: {cell[1]}, size: {cell[2]} }}\n"
        "} as const;\n"
    )

    # Standalone: overshoot inside the box, dark-mode colours from the reader's preference.
    vb = f"0 {num(top)} {num(width)} {num(bottom - top)}"
    (ROOT / "web/static/mark.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" role="img" aria-label="T32">'
        f"<style>.n{{fill:{INK}}}.c{{fill:{ACCENT}}}"
        f"@media (prefers-color-scheme:dark){{.n{{fill:{DARK_INK}}}.c{{fill:{DARK_ACCENT}}}}}</style>"
        f'<path class="n" d="{d}"/>'
        f'<rect class="c" x="{cell[0]}" y="{cell[1]}" width="{cell[2]}" height="{cell[2]}"/></svg>\n'
    )

    # Favicon: measure at unit scale, then fit the name across the tile and centre its cap height.
    _, r1, _, _ = outline(FAVICON_WEIGHT, 1, 0, 0)
    fs = (TILE - 2 * TILE_PAD) / r1
    fd, _, _, _ = outline(FAVICON_WEIGHT, fs, TILE_PAD, (TILE + cap * fs) / 2)
    # A dark tile vanishes on a dark tab strip, so in the dark scheme it turns to paper.
    (ROOT / "web/static/favicon.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {TILE} {TILE}">'
        f"<style>.t{{fill:{INK}}}.n{{fill:{PAPER}}}"
        f"@media (prefers-color-scheme:dark){{.t{{fill:{DARK_INK}}}.n{{fill:{DARK_PAPER}}}}}</style>"
        f'<rect class="t" width="{TILE}" height="{TILE}" rx="5"/>'
        f'<path class="n" d="{fd}"/></svg>\n'
    )


if __name__ == "__main__":
    main()
